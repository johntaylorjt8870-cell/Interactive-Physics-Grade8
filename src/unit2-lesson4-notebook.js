const escapeHtml = (value) => String(value)
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;')
  .replaceAll("'", '&#39;');

const inline = (source, reading) => tex(source, reading);
const ltr = (value) => `<bdi class="r4nb-ltr" dir="ltr">${escapeHtml(value)}</bdi>`;
const bookTag = '<span class="r4nb-tag r4nb-tag-book">من الكتاب</span>';
const platformTag = '<span class="r4nb-tag r4nb-tag-platform">إثراء من المنصة</span>';
const inferenceTag = '<span class="r4nb-tag r4nb-tag-inference">استنتاج تعليمي · لا يطبعه الكتاب</span>';
const caveatTag = '<span class="r4nb-tag r4nb-tag-caveat">قيد مصدر موثّق</span>';

const definition = (term, body, source = bookTag) => `<div class="r4nb-definition"><strong>${term}</strong><span>${body}</span>${source}</div>`;
const displayEquation = (source, reading, label = '') => `<div class="r4nb-equation"${label ? ` aria-label="${escapeHtml(label)}"` : ''}>${formula(source, reading)}</div>`;
const law = (title, source, reading, condition, provenance = bookTag) => `<article class="r4nb-law">
  <div class="r4nb-law-title"><strong>${title}</strong>${provenance}</div>
  ${displayEquation(source, reading)}
  ${condition ? `<p class="r4nb-law-condition"><strong>شرط/طريقة الاستخدام:</strong> ${condition}</p>` : ''}
</article>`;
const note = (body, kind = 'source') => `<aside class="r4nb-note r4nb-note-${kind}">${body}</aside>`;
const list = (items, className = '') => `<ul${className ? ` class="${className}"` : ''}>${items.map((item) => `<li>${item}</li>`).join('')}</ul>`;
const ordered = (items, className = '') => `<ol${className ? ` class="${className}"` : ''}>${items.map((item) => `<li>${item}</li>`).join('')}</ol>`;
const subsection = (title, body, source = '') => `<div class="r4nb-subsection">${source ? `<p class="r4nb-subsection-source">${source}</p>` : ''}<h4>${title}</h4>${body}</div>`;

let tableSequence = 0;
const table = ({ caption, head, rows, rowHead = false, dir = 'rtl', className = '' }) => {
  const captionId = `u2l4nb-table-${tableSequence += 1}`;
  return `<div class="r4nb-table-wrap" role="region" aria-labelledby="${captionId}" tabindex="0">
  <table class="r4nb-table${className ? ` ${className}` : ''}" dir="${dir}">
    <caption id="${captionId}">${caption}</caption>
    <thead><tr>${head.map((cell) => `<th scope="col">${cell}</th>`).join('')}</tr></thead>
    <tbody>${rows.map((row) => `<tr>${row.map((cell, index) => rowHead && index === 0
      ? `<th scope="row">${cell}</th>`
      : `<td>${cell}</td>`).join('')}</tr>`).join('')}</tbody>
  </table>
</div>`;
};

const section = (id, title, page, body) => `<section class="r4nb-section" data-notebook-section="${id}" data-source-page="${page}" aria-labelledby="${id}">
  <h3 id="${id}">${title}</h3>
  <div class="r4nb-section-body">${body}</div>
</section>`;

const activityById = new Map(ACTIVITIES.map((activity) => [activity.id, activity]));
if (activityById.size !== ACTIVITIES.length) throw new Error('Lesson 4 source activity IDs must be unique.');

const activityCard = (id) => {
  const activity = activityById.get(id);
  if (!activity) throw new RangeError(`Unknown Lesson 4 source activity: ${id}`);
  return `<article class="r4nb-source-demand" data-source-activity="${escapeHtml(activity.id)}" data-source-page="p${activity.page}">
    <div class="r4nb-source-demand-head">${bookTag}<span class="r4nb-source-page" dir="ltr">p${activity.page}</span><strong>${escapeHtml(activity.label)}</strong></div>
    <p>${escapeHtml(activity.prompt)}</p>
    <a href="#p${activity.page}" class="r4nb-open-source">افتح نشاط الصفحة في الدرس <span aria-hidden="true">←</span></a>
  </article>`;
};

const activitiesForPage = (page) => {
  const items = ACTIVITIES.filter((activity) => activity.page === page);
  if (!items.length) return '';
  return `<div class="r4nb-source-group" aria-label="مطالب المصدر في الصفحة ${page}">
    <h4>مطالب الكتاب وأنشطته في ص ${ltr(page)} ${bookTag}</h4>
    <p class="r4nb-source-group-note">هذه مطالب المصدر كاملةً بحسب سجل التدقيق؛ استخدم رابط كل بطاقة لفتح النشاط والتلميح/الحل بعد المحاولة.</p>
    <div class="r4nb-source-demand-grid">${items.map((activity) => activityCard(activity.id)).join('')}</div>
  </div>`;
};


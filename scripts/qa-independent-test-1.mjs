/* Real-browser acceptance for Test 1 inside independent-tests.html.
 * Run after `npm run build` and while a static server serves the repo root.
 * QA_MODULE_DIR and QA_CHROMIUM allow Chromium/Playwright to live outside git.
 */
import { createRequire } from 'node:module';
const requireFromQa = createRequire(process.env.QA_MODULE_DIR ? `${process.env.QA_MODULE_DIR}/` : import.meta.url);
const { chromium } = requireFromQa('playwright-core');
const BASE = process.env.QA_BASE_URL ?? 'http://127.0.0.1:4173';
const PAGE_URL = `${BASE}/dist/independent-tests.html`;
const browser = await chromium.launch({
  executablePath: process.env.QA_CHROMIUM ?? '/tmp/chromium',
  headless: true,
  args: ['--no-sandbox', '--disable-dev-shm-usage'],
  timeout: 60000,
});
const errors = [];
const results = [];
const check = (name, ok, detail = '') => {
  results.push({ name, ok, detail });
  if (!ok) console.error(`FAIL ${name}${detail ? ` — ${detail}` : ''}`);
};
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const requests = [];
page.on('request', (request) => requests.push(request.url()));
page.on('pageerror', (error) => errors.push(String(error)));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });

await page.goto(PAGE_URL, { waitUntil: 'networkidle' });
check('one central independent-tests page loads', await page.title().then((title) => title.includes('اختبارات مستقلة')));
check('registry renders one current test card', await page.locator('.it-card').count() === 1);
check('registry card opens by stable id in the same URL', (await page.locator('.it-card-action').getAttribute('href')) === '#test-01');
check('no standalone assessment route exists in the registry or page', !(await page.locator('a[href*="independent-test-1.html"]').count()));
check('solution code is not requested from the catalog', !requests.some((url) => url.includes('it1-solutions')));

await page.click('.it-card-action');
await page.waitForSelector('[role="tablist"][aria-label="مسائل الاختبار الأربع عشرة"]');
const tabs = page.locator('[role="tab"]');
check('exactly 14 problem tabs are rendered', await tabs.count() === 14);
const tabNames = await tabs.allInnerTexts();
check('tab names run first through fourteenth in order',
  tabNames.map((text) => text.replace(/\s+/g, ' ').trim()).join('|') === [
    '1 المسألة الأولى','2 المسألة الثانية','3 المسألة الثالثة','4 المسألة الرابعة','5 المسألة الخامسة',
    '6 المسألة السادسة','7 المسألة السابعة','8 المسألة الثامنة','9 المسألة التاسعة','10 المسألة العاشرة',
    '11 المسألة الحادية عشرة','12 المسألة الثانية عشرة','13 المسألة الثالثة عشرة','14 المسألة الرابعة عشرة',
  ].join('|'), tabNames.join(' / '));
check('one and only one tab and panel are active',
  await page.locator('[role="tab"][aria-selected="true"]').count() === 1
  && await page.locator('[role="tabpanel"]:not([hidden])').count() === 1);
check('question statement is separate from givens and requested responses',
  await page.locator('#it1-panel-1 .it1-question-statement').count() === 1
  && await page.locator('#it1-panel-1 .it1-givens-block').count() === 1
  && await page.locator('#it1-panel-1 .it1-asks-block').count() === 1);
check('no diagram appears with the prompt before submission', await page.locator('.it1-problem-panel:not([hidden]) .it1-diagram').count() === 0);
check('all 14 solution slots remain hidden before submission',
  await page.locator('.it1-solution-slot[hidden]').count() === 14);
check('current position is exposed as problem 1 of 14', (await page.locator('#it1-live-status').innerText()).includes('1 من 14'));
check('physical resultant notation is F in public problem data',
  !/\bR\s*=|المحصلة\s*R|شدة\s*R/u.test(await page.evaluate(async () => JSON.stringify((await import('./src/it1-problems.js')).IT1_PROBLEMS))));

// ARIA keyboard navigation follows the RTL tab row and wraps between problems.
await page.locator('#it1-tab-1').focus();
await page.keyboard.press('ArrowLeft');
check('ArrowLeft selects and focuses the adjacent problem tab',
  await page.locator('#it1-tab-2').getAttribute('aria-selected') === 'true'
  && await page.evaluate(() => document.activeElement?.id === 'it1-tab-2'));
await page.keyboard.press('End');
check('End selects the fourteenth tab', await page.locator('#it1-tab-14').getAttribute('aria-selected') === 'true');
await page.keyboard.press('Home');
check('Home returns to the first tab', await page.locator('#it1-tab-1').getAttribute('aria-selected') === 'true');

// Visit every problem at all three acceptance viewport sizes. One desktop
// screenshot per problem is generated by qa-shots-independent-test-1.mjs.
for (const [width, height] of [[1440, 900], [1366, 768], [390, 844]]) {
  await page.setViewportSize({ width, height });
  for (let index = 0; index < 14; index += 1) {
    await page.locator(`#it1-tab-${index + 1}`).click();
    const panel = page.locator(`#it1-panel-${index + 1}`);
    check(`${width}px problem ${index + 1}: correct panel and matching tab activate`,
      await panel.isVisible() && await page.locator(`#it1-tab-${index + 1}`).getAttribute('aria-selected') === 'true');
    check(`${width}px problem ${index + 1}: no prompt-side diagram`, await panel.locator('.it1-diagram').count() === 0);
    check(`${width}px problem ${index + 1}: solution is still gated`, await panel.locator('.it1-solution-slot').evaluate((node) => node.hidden));
    const pageWidth = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
    check(`${width}px problem ${index + 1}: no page-level horizontal overflow`, pageWidth <= 1, `${pageWidth}px`);
  }
}

const answerKeys = {
  'it1p01-magnitude': '60', 'it1p01-d1': '1.5', 'it1p01-d2': '0.5',
  'it1p02-magnitude': '80', 'it1p02-elements': 'full', 'it1p02-d1': '0.2', 'it1p02-d2': '0.6',
  'it1p03-magnitude': '400', 'it1p03-d2': '0.25', 'it1p03-total': '1',
  'it1p04-magnitude': '60', 'it1p04-d1': '0.9', 'it1p04-d2': '0.3',
  'it1p05-f2': '160', 'it1p05-elements': 'outside-larger', 'it1p05-d1': '0.8', 'it1p05-total': '0.6',
  'it1p06-elements': 'full', 'it1p06-d2': '0.5', 'it1p06-total': '1.5',
  'it1p07-elements': 'diagonal', 'it1p07-magnitude': '5', 'it1p07-alpha': '53.1',
  'it1p08-magnitude': '20', 'it1p08-tan': '0.75',
  'it1p09-elements': 'bisector', 'it1p09-magnitude': '8.49', 'it1p09-alpha': '45',
  'it1p10-magnitude': '28.28', 'it1p10-shape': 'square-diagonal',
  'it1p11-construction': 'complete', 'it1p11-elements': 'full',
  'it1p12-elements': 'inside', 'it1p12-angle-effect': 'inverse',
  'it1p13-magnitude': '86.6', 'it1p13-elements': 'bisector',
  'it1p14-elements': 'bisector', 'it1p14-magnitude': '138.6', 'it1p14-alpha': '30',
};
const questionMeta = await page.evaluate(async () => (await import('./src/it1-problems.js')).IT1_QUESTIONS.map(({ id, problemId, type }) => ({ id, problemId, type })));
let filled = 0;
for (const question of questionMeta) {
  const problemNumber = Number(question.problemId.slice(-2));
  await page.locator(`#it1-tab-${problemNumber}`).click();
  const answer = answerKeys[question.id];
  if (answer === undefined) throw new Error(`Missing QA value for ${question.id}`);
  if (question.type === 'single-choice') {
    await page.locator(`[data-question-id="${question.id}"][type="radio"][value="${answer}"]`).check();
  } else {
    await page.locator(`[data-question-id="${question.id}"][type="text"]`).fill(answer);
  }
  filled += 1;
}
check('all source-requested answer fields accept input', filled === 39, String(filled));
check('answered count reflects all 39 fields', (await page.locator('#it1-progress-copy').innerText()).includes('39 من 39'));
check('no answer module was fetched before submit', !requests.some((url) => url.includes('it1-solutions')));
await page.locator('[data-it1-submit]').click();
await page.waitForSelector('#it1-result-summary:not([hidden])', { timeout: 20000 });
check('submission requests the answer module', requests.some((url) => url.includes('it1-solutions')));
check('a fully correct response earns 39 / 39', (await page.locator('#it1-result-summary').innerText()).includes('39 / 39'));
check('the 14 solutions and their figures appear after submit',
  await page.locator('.it1-solution-slot:not([hidden])').count() === 14
  && await page.locator('.it1-solution-slot .it1-diagram').count() === 14);
check('every resultant arrow is labelled F',
  await page.locator('.it1-solution-slot .it1-force-solved').count() >= 14
  && !/\bR\s*=|المحصلة\s*R/u.test(await page.locator('#it1-assessment').innerText()));

// Check the required real viewport sizes and locally-contained tab scrolling.
for (const [width, height] of [[1440, 900], [1366, 768], [390, 844]]) {
  await page.setViewportSize({ width, height });
  await page.locator('#it1-tab-7').click();
  const metrics = await page.evaluate(() => ({
    viewport: innerWidth,
    pageWidth: document.documentElement.scrollWidth,
    activePanel: document.querySelector('[role="tabpanel"]:not([hidden])')?.getBoundingClientRect().width,
    tabScroll: document.querySelector('.it1-tab-scroll').scrollWidth > document.querySelector('.it1-tab-scroll').clientWidth,
  }));
  check(`${width}px viewport has no page-level horizontal overflow`, metrics.pageWidth <= metrics.viewport + 1, JSON.stringify(metrics));
  check(`${width}px viewport shows exactly one problem panel`, await page.locator('[role="tabpanel"]:not([hidden])').count() === 1);
  if (width === 390) check('390px uses contained horizontal tab scrolling', metrics.tabScroll);
  else check(`${width}px tablist fits without horizontal scroll`, !metrics.tabScroll);
}
check('no console or uncaught page errors', errors.length === 0, errors.join(' | ').slice(0, 500));

await browser.close();
const failed = results.filter((result) => !result.ok);
console.log(`\n${results.length - failed.length}/${results.length} browser checks passed`);
if (failed.length) {
  for (const item of failed) console.log(` - ${item.name}${item.detail ? `: ${item.detail}` : ''}`);
  process.exitCode = 1;
}
